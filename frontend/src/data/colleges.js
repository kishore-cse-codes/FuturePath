export const COLLEGE_MAP = new Map(COLLEGES.map((college) => [college.id, college]))

export const COLLEGE_TYPES = [...new Set(COLLEGES.map((college) => college.type))].sort()

export const COLLEGE_LOCATIONS = [...new Set(COLLEGES.map((college) => college.location))].sort()

export function getCollegeById(id) {
  return COLLEGE_MAP.get(id) ?? null
}

export function getCollegesForStream(streamCode) {
  const code = String(streamCode ?? '').toUpperCase()
  if (!code) return COLLEGES
  return COLLEGES.filter((college) =>
    college.streamCodes.some((item) => item.toUpperCase() === code),
  )
}
